import {mkdirSync, readFileSync, writeFileSync} from "node:fs"
import {resolve, dirname} from "node:path"
import {fileURLToPath} from "node:url"
import {COLORS, CSS_VARIABLES, FONT_SIZES, RADIUS, SPACING} from "../src/assets/style/tokens.ts"

// 两端共用令牌，生成产物提交到仓库，独立 .NET 构建无需执行 Node。
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const CHECK = process.argv.includes("--check")
const PASCAL = name => name.split(/[-.]/).map(part => part[0].toUpperCase() + part.slice(1)).join("")
const NATIVE_COLOR = value => {
	if (/^#[\da-f]{6}$/i.test(value)) return value.toUpperCase()
	const MATCH = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value)
	if (!MATCH) throw new Error(`不支持的颜色令牌：${value}`)
	return "#" + [Math.round(Number(MATCH[4]) * 255), ...MATCH.slice(1, 4).map(Number)]
		.map(channel => channel.toString(16).padStart(2, "0")).join("").toUpperCase()
}
const LOGICAL = value => Number.parseFloat(value) * (value.endsWith("rem") ? 10 : 1)
const write = (path, content) => {
	const FILE = resolve(ROOT, path)
	let previous = ""
	try { previous = readFileSync(FILE, "utf8") } catch (error) { if (error.code !== "ENOENT") throw error }
	if (previous.replaceAll("\r\n", "\n") === content) return
	if (CHECK) {
		process.stderr.write(`设计令牌未同步：${path}，请执行 pnpm theme:sync\n`)
		process.exitCode = 1
		return
	}
	mkdirSync(dirname(FILE), {recursive: true})
	writeFileSync(FILE, content)
}

const ENTRIES = Object.entries(COLORS)
const VALUES = ENTRIES.map(([key, value]) => `\t\t["${key}"] = "${NATIVE_COLOR(value)}",`).join("\n")
const MEASURES = [
	...Object.entries(RADIUS).map(([key, value]) => [`radius-${key}`, LOGICAL(value)]),
	...Object.entries(SPACING).map(([key, value]) => [`spacing-${key}`, LOGICAL(value)]),
	...Object.entries(FONT_SIZES).map(([key, value]) => [`font-${key}`, LOGICAL(value[0])]),
]
write("Nori.Desktop/Appearance/NoriThemeTokens.g.cs", `// <auto-generated />
// 来源：src/assets/style/tokens.ts；请使用 pnpm theme:sync 同步。
using Avalonia.Media;
using Avalonia.Media.Immutable;

namespace Nori.Desktop.Appearance;

/// <summary>Web 与原生共享的深色设计令牌；静态画刷没有 UI 线程所有权。</summary>
internal static class NoriThemeTokens
{
\tprivate static readonly IReadOnlyDictionary<string, string> Values = new Dictionary<string, string>
\t{
${VALUES}
\t};
\tprivate static readonly IReadOnlyDictionary<string, IBrush> Brushes = Values.ToDictionary(
\t\tpair => pair.Key, pair => (IBrush)new ImmutableSolidColorBrush(Avalonia.Media.Color.Parse(pair.Value)));
\tprivate static readonly IReadOnlyDictionary<string, double> Measures = new Dictionary<string, double>
\t{
${MEASURES.map(([key, value]) => `\t\t["${key}"] = ${value},`).join("\n")}
\t};

\tinternal static string Value(string name) => Values[name];
\tinternal static Color Color(string name) => Avalonia.Media.Color.Parse(Value(name));
\tinternal static IBrush Brush(string name) => Brushes[name];
\tinternal static double Measure(string name) => Measures[name];
}
`)

write("Nori.Desktop/Appearance/NoriThemeResources.g.axaml", `<!-- 自动生成；来源：src/assets/style/tokens.ts。请使用 pnpm theme:sync 同步。 -->
<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
${ENTRIES.map(([key, value]) => `\t<Color x:Key="Nori${PASCAL(key)}Color">${NATIVE_COLOR(value)}</Color>\n\t<SolidColorBrush x:Key="Nori${PASCAL(key)}Brush" Color="{StaticResource Nori${PASCAL(key)}Color}"/>`).join("\n")}
\t<StaticResource x:Key="NoriWindowSurfaceBrush" ResourceKey="NoriBgBaseBrush"/>
</ResourceDictionary>
`)

const THEME_PATH = "src/assets/style/theme.less"
const THEME = readFileSync(resolve(ROOT, THEME_PATH), "utf8").replaceAll("\r\n", "\n")
if (!/:root\s*\{[\s\S]*?\n\}/.test(THEME)) throw new Error("theme.less 缺少 :root 令牌块")
write(THEME_PATH, THEME.replace(/:root\s*\{[\s\S]*?\n\}/,
	`:root {\n${Object.entries(CSS_VARIABLES).map(([key, value]) => `\t${key}: ${value};`).join("\n")}\n}`))
